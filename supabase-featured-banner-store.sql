create table if not exists public.featured_banners (
  id bigint generated by default as identity primary key,
  title text not null,
  subtitle text not null,
  badge_text text not null default 'FEATURED EVENT',
  primary_button_text text not null,
  primary_button_link text not null,
  secondary_button_text text,
  secondary_button_link text,
  background_style text not null default 'red',
  image_url text,
  is_active boolean not null default false,
  "order" integer not null default 0,
  start_date timestamptz,
  end_date timestamptz,
  display_frequency text not null default 'every_visit',
  is_emergency boolean not null default false,
  show_countdown boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.featured_banners
  add column if not exists display_frequency text not null default 'every_visit',
  add column if not exists is_emergency boolean not null default false,
  add column if not exists show_countdown boolean not null default false;
alter table public.featured_banners
  add column if not exists image_url text;

