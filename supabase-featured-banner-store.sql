create table if not exists public.store_products (
  id bigint generated by default as identity primary key,
  name text not null,
  price integer not null default 0,
  image_url text,
  description text,
  is_preorder boolean not null default false,
  is_active boolean not null default false,
  "order" integer not null default 0,
  created_at timestamptz not null default now()
);

alter table public.featured_banners enable row level security;
alter table public.store_products enable row level security;

drop policy if exists "Public can read active featured banners" on public.featured_banners;
create policy "Public can read active featured banners"
  on public.featured_banners for select using (is_active = true);
drop policy if exists "Public can read active store products" on public.store_products;
create policy "Public can read active store products"
  on public.store_products for select using (is_active = true);
